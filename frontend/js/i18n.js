// --- Translation Engine ---
function applyTranslation(lang) {
  const t = translations[lang];
  if (!t) return;

  // Apply data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // Apply data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });

  // Update lang button label
  const langLabel = document.getElementById('langLabel');
  if (langLabel) langLabel.textContent = t['lang_label'];

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Save preference
  localStorage.setItem('bjo_lang', lang);
}

function initI18n() {
  // Load saved language or default to 'en'
  const saved = localStorage.getItem('bjo_lang') || 'en';
  applyTranslation(saved);

  // Bind language switcher buttons
  document.querySelectorAll('[data-lang]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      applyTranslation(btn.getAttribute('data-lang'));
    });
  });
}

// Auto-init when DOM is ready
document.addEventListener('DOMContentLoaded', initI18n);
